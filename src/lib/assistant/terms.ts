import type { Selection, Terms } from "./types";
import type { ProductDetail } from "../catalog/types";

export function purchaseTerms(
  topics: Selection["topics"],
  language: "ru" | "kk",
  product?: ProductDetail,
): Terms[] {
  const kk = language === "kk";
  const data = {
    payment: {
      title: kk ? "Төлем" : "Оплата",
      text: kk
        ? "Жеке тұлғалар: сайтта карта арқылы, тауарды алған кезде қолма-қол немесе дүкенде төлеу. Заңды тұлғалар: шот бойынша аударым немесе өздері алып кеткенде дүкенде қолма-қол төлеу. Бұл прототип төлем қабылдамайды."
        : "Физлицам доступны карта на сайте, наличные при получении и оплата в торговом зале при самовывозе. Юрлицам — перевод по выставленному счёту либо наличные в торговом зале при самовывозе. Прототип оплату не принимает.",
    },
    delivery: {
      title: kk ? "Жеткізу" : "Доставка",
      text: kk
        ? "EKT сайтында Алматыда менеджермен келісілген тауарды 48 сағат ішінде жеткізу көрсетілген. Басқа қалаларға мерзім мен құн мекенжайға, салмаққа және көлемге байланысты келісіледі. Қоймадан алып кетуге болады. Сайттағы тегін жеткізу шектері біркелкі емес, нақты құнын растау қажет."
        : "Для Алматы на странице EKT указан срок до 48 часов после согласования товара с менеджером. В другие города сроки и стоимость согласуются по адресу, весу и объёму. Доступен самовывоз из городов присутствия. На сайте встречаются разные пороги бесплатной доставки — точную стоимость нужно подтвердить; обещания даты для конкретного заказа нет.",
    },
    minimum: {
      title: kk ? "Ең аз партия" : "Минимальная партия",
      text: kk
        ? "Жалпы ең аз тапсырыс көлемі дереккөзде көрсетілмеген. Тауар карточкасындағы еселік өрісі ең аз партияны автоматты түрде білдірмейді. Нақты артикул бойынша растау керек."
        : "Общая минимальная сумма или партия в проверенном источнике не указана. Поле кратности в карточке товара не считаем автоматически минимальной партией — условие нужно подтвердить для конкретного артикула.",
    },
  };
  if (product?.properties.KRATNOST_MIN) {
    data.minimum.text = kk
      ? `${product.article}: API-дегі сату еселігі — ${product.properties.KRATNOST_MIN}. Тапсырыстың ең аз жалпы сомасы дереккөзде көрсетілмеген. Еселік пен ең аз сома — бөлек шарттар.`
      : `Для ${product.article} кратность продажи в API — ${product.properties.KRATNOST_MIN}. Это шаг количества товара. Минимальная общая сумма заказа в источнике не указана; кратность и минимальная сумма — разные условия.`;
  }
  return [...new Set(topics)].map((topic) => ({
    ...data[topic],
    url:
      topic === "minimum" && product?.properties.KRATNOST_MIN
        ? product.url || product.source
        : "https://ekt.kz/checkout-delivery/",
    checkedAt: "2026-09-23",
  }));
}
